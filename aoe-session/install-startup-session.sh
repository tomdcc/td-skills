#!/usr/bin/env bash
# Install (or remove) a launchd LaunchAgent that creates + starts a named aoe
# Claude session at login. aoe sessions are tmux-backed, so they do NOT survive
# a reboot; this agent recreates the session each login (idempotent — skipped if
# a session of that name is already present).
#
# Companion to install-daemon.sh: that keeps `aoe serve` up; this puts one
# standing session on top of it. The generated runner waits for the serve
# daemon before adding the session.
#
# Portable: machine-specific paths are resolved at runtime and the emitted
# runner + plist are self-contained (independent of this repo's location).
#
# Usage:  ./install-startup-session.sh <session-name> <directory> [profile]
#         ./install-startup-session.sh --uninstall <session-name>
#
#   session-name  aoe session title (also the --remote-control name)
#   directory     cwd for the session (created if missing)
#   profile       aoe profile / Claude account (default: personal)
set -euo pipefail

AGENT_PREFIX="com.tomdunstan.aoe-session"

if [ "${1:-}" = "--uninstall" ]; then
  name="${2:?usage: $0 --uninstall <session-name>}"
  label="$AGENT_PREFIX-$name"
  launchctl bootout "gui/$(id -u)/$label" 2>/dev/null || true
  rm -f "$HOME/Library/LaunchAgents/$label.plist" "$HOME/.agent-of-empires/startup-session-$name.sh"
  echo "Removed $label (session '$name' left running if present — stop with: aoe rm '$name')"
  exit 0
fi

NAME="${1:?usage: $0 <session-name> <directory> [profile]}"
DIR="${2:?usage: $0 <session-name> <directory> [profile]}"
PROFILE="${3:-personal}"
LABEL="$AGENT_PREFIX-$NAME"
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
RUNNER="$HOME/.agent-of-empires/startup-session-$NAME.sh"
DOMAIN="gui/$(id -u)"

# --- preconditions -----------------------------------------------------------
command -v aoe >/dev/null || { echo "ERROR: aoe not found. Install with: brew install aoe" >&2; exit 1; }
[ -d "$HOME/.agent-of-empires/profiles/$PROFILE" ] || {
  echo "ERROR: aoe profile '$PROFILE' not found — run setup-profiles.sh first." >&2; exit 1; }
AOE_BIN="$(command -v aoe)"
BREW_PREFIX="$(brew --prefix 2>/dev/null || echo /usr/local)"
PATH_ENV="$HOME/.local/bin:$BREW_PREFIX/bin:/usr/bin:/bin:/usr/sbin:/sbin"

mkdir -p "$HOME/.agent-of-empires" "$HOME/Library/LaunchAgents" "$HOME/Library/Logs"

# --- generate the self-contained runner --------------------------------------
# Config values are baked in at install time; runtime vars are escaped (\$).
cat > "$RUNNER" <<EOF
#!/usr/bin/env bash
# Auto-generated by install-startup-session.sh — recreated on reinstall.
set -euo pipefail
export PATH="$PATH_ENV"
NAME="$NAME"
DIR="$DIR"
PROFILE="$PROFILE"

mkdir -p "\$DIR"

# Wait for the serve daemon (started by its own LaunchAgent) — up to ~60s.
for _ in \$(seq 1 60); do aoe url >/dev/null 2>&1 && break; sleep 1; done

# Idempotent: do nothing if a session of this name already exists.
if aoe list --json -p "\$PROFILE" 2>/dev/null | grep -q "\"\$NAME\""; then
  echo "session '\$NAME' already present — nothing to do"
  exit 0
fi

# allow_remote = restrictions.allow_remote_control.allowed from the profile's
# CLAUDE_CONFIG_DIR policy-limits.json (true when the file is absent).
CFG="\$(grep -o 'CLAUDE_CONFIG_DIR=[^\"]*' "\$HOME/.agent-of-empires/profiles/\$PROFILE/config.toml" | head -1 | cut -d= -f2)"
CFG="\${CFG:-\$HOME/.claude}"
allow_remote=1
if [ -f "\$CFG/policy-limits.json" ]; then
  allow_remote="\$(python3 -c 'import json,sys;print(1 if json.load(open(sys.argv[1])).get("restrictions",{}).get("allow_remote_control",{}).get("allowed",True) else 0)' "\$CFG/policy-limits.json" 2>/dev/null || echo 1)"
fi

# Group = base repo: resolve via git (robust to any worktree layout — a linked
# worktree's --git-common-dir points at the main checkout), else the dir basename.
CD_COMMON="\$(git -C "\$DIR" rev-parse --path-format=absolute --git-common-dir 2>/dev/null)"
if [ -n "\$CD_COMMON" ]; then GROUP="\$(basename "\$(dirname "\$CD_COMMON")")"; else GROUP="\$(basename "\$DIR")"; fi

if [ "\$allow_remote" = "1" ]; then
  aoe add "\$DIR" -t "\$NAME" -p "\$PROFILE" -g "\$GROUP" --cmd claude --extra-args "--remote-control \$NAME"
else
  aoe add "\$DIR" -t "\$NAME" -p "\$PROFILE" -g "\$GROUP" --cmd claude
fi
aoe session start "\$NAME" -p "\$PROFILE"
echo "started session '\$NAME' in \$DIR (profile \$PROFILE, remote_control=\$allow_remote)"
EOF
chmod +x "$RUNNER"

# --- generate the plist (one-shot at login; no KeepAlive) ---------------------
cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>$RUNNER</string>
    </array>
    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>$PATH_ENV</string>
    </dict>
    <key>RunAtLoad</key>
    <true/>
    <!-- Interactive, not Background: the tmux sessions this starts are for interactive use. Background QoS confines the
         job, and everything it starts (the tmux server, its sessions, Gradle daemons and test JVMs), to the
         efficiency cores, which made builds about 4x slower; Standard still applies light CPU and I/O limits. -->
    <key>ProcessType</key>
    <string>Interactive</string>
    <key>StandardOutPath</key>
    <string>$HOME/Library/Logs/aoe-session-$NAME.out.log</string>
    <key>StandardErrorPath</key>
    <string>$HOME/Library/Logs/aoe-session-$NAME.err.log</string>
</dict>
</plist>
EOF

plutil -lint "$PLIST" >/dev/null

# --- (re)load ----------------------------------------------------------------
launchctl bootout "$DOMAIN/$LABEL" 2>/dev/null || true
for _ in $(seq 1 25); do
  launchctl print "$DOMAIN/$LABEL" >/dev/null 2>&1 || break
  sleep 0.2
done
launchctl bootstrap "$DOMAIN" "$PLIST"

echo "Installed $LABEL"
echo "  session: $NAME  (profile $PROFILE)"
echo "  dir:     $DIR"
echo "  runner:  $RUNNER"
echo "  plist:   $PLIST"
echo "  logs:    $HOME/Library/Logs/aoe-session-$NAME.{out,err}.log"
echo "It runs at each login; to create the session now: launchctl kickstart $DOMAIN/$LABEL"
